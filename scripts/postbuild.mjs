// Writes dist/sw.js: a service worker that keeps every built file on the laptop,
// so Staffroom opens with no connection. No library is used.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = 'dist';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(dist)
  .map((path) => '/' + relative(dist, path).split('\\').join('/'))
  .filter((path) => path !== '/sw.js');

const hash = createHash('sha256');
for (const file of files) hash.update(file).update(readFileSync(join(dist, file)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/postbuild.mjs. Do not edit.
const CACHE = 'staffroom-${version}';
const FILES = ${JSON.stringify(['/', ...files])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('staffroom-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  // Only this site's own files. Requests to Firebase and Google are never touched or stored.
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const key = request.mode === 'navigate' ? '/' : request;
    const hit = await cache.match(key, { ignoreSearch: true, ignoreVary: true });
    if (hit) return hit;
    return fetch(request);
  })());
});
`;

writeFileSync(join(dist, 'sw.js'), sw);

const kb = (path) => (statSync(join(dist, path)).size / 1024).toFixed(1);
console.log(`sw.js written: cache staffroom-${version}, ${files.length} files`);
for (const file of files.filter((f) => /\.(js|css|html)$/.test(f))) console.log(`  ${kb(file).padStart(8)} KB  ${file}`);
